"""Aggregate experiment results and create report-ready outputs."""

from __future__ import annotations

import argparse
import csv
import glob
import os
from collections import defaultdict

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", default="outputs/evaluation/results.csv")
    parser.add_argument("--output-dir", default="outputs/evaluation")
    return parser.parse_args(argv)


def read_results(path):
    rows = []
    with open(path, newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            for key in (
                "run",
                "block_size",
                "num_blocks",
                "rank",
                "max_iter",
                "iterations",
                "sample_count",
            ):
                row[key] = int(row[key])
            row["min_iter"] = int(row["min_iter"]) if row.get("min_iter") else None
            row["patience"] = int(row["patience"]) if row.get("patience") else None
            for key in (
                "nominal_occluded_fraction",
                "actual_occluded_fraction",
                "observed_changed_fraction",
                "sample_frac",
                "actual_sample_frac",
                "rre",
                "runtime_seconds",
                "initial_training_loss",
                "final_training_loss",
            ):
                row[key] = float(row[key])
            for key in ("include_size_sweep", "include_count_sweep"):
                row[key] = row[key].lower() == "true"
            row["tol"] = float(row["tol"]) if row.get("tol") else None
            for key in ("accuracy", "nmi"):
                row[key] = float(row[key]) if row[key] else None
            rows.append(row)
    if not rows:
        raise ValueError("results file contains no experiment rows")
    return rows


def aggregate_results(rows):
    grouped = defaultdict(list)
    for row in rows:
        key = (
            row["dataset"],
            row["condition_id"],
            row["block_size"],
            row["num_blocks"],
            row["algorithm"],
        )
        grouped[key].append(row)

    summary = []
    algorithm_order = {"standard_nmf": 0, "robust_l1_nmf": 1}
    ordered_groups = sorted(
        grouped.items(),
        key=lambda item: (
            item[0][0],
            item[0][2] != 0 or item[0][3] != 0,
            item[0][2],
            item[0][3],
            algorithm_order.get(item[0][4], 99),
        ),
    )
    for key, group in ordered_groups:
        run_ids = [row["run"] for row in group]
        if len(run_ids) != len(set(run_ids)):
            raise ValueError(f"duplicate trial rows found for {key}")
        rre = np.asarray([row["rre"] for row in group], dtype=float)
        runtime = np.asarray([row["runtime_seconds"] for row in group], dtype=float)
        accuracies = [row["accuracy"] for row in group if row["accuracy"] is not None]
        nmis = [row["nmi"] for row in group if row["nmi"] is not None]
        summary.append({
            "dataset": key[0],
            "condition_id": key[1],
            "block_size": key[2],
            "num_blocks": key[3],
            "algorithm": key[4],
            "runs": len(group),
            "mean_rre": float(rre.mean()),
            "std_rre": float(rre.std(ddof=1)) if len(rre) > 1 else 0.0,
            "mean_runtime_seconds": float(runtime.mean()),
            "std_runtime_seconds": float(runtime.std(ddof=1)) if len(runtime) > 1 else 0.0,
            "mean_accuracy": float(np.mean(accuracies)) if accuracies else "",
            "std_accuracy": (
                float(np.std(accuracies, ddof=1)) if len(accuracies) > 1
                else (0.0 if accuracies else "")
            ),
            "mean_nmi": float(np.mean(nmis)) if nmis else "",
            "std_nmi": (
                float(np.std(nmis, ddof=1)) if len(nmis) > 1
                else (0.0 if nmis else "")
            ),
        })
    return summary


def write_summary_csv(path, summary):
    fields = list(summary[0])
    with open(path, "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(summary)


def write_latex_table(path, summary):
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("% Generated by plot_results.py\n")
        handle.write("\\begin{table}[t]\n\\centering\n")
        handle.write(
            "\\caption{Mean Relative Reconstruction Error (RRE) "
            "across repeated trials.}\n"
        )
        handle.write("\\label{tab:rre-summary}\n")
        handle.write("\\begin{tabular}{llrrrc}\n\\toprule\n")
        handle.write("Dataset & Algorithm & $b$ & $k$ & $n$ & RRE (mean $\\pm$ std) \\\\\n")
        handle.write("\\midrule\n")
        for row in summary:
            algorithm = _algorithm_label(row["algorithm"])
            handle.write(
                f"{row['dataset']} & {algorithm} & {row['block_size']} & "
                f"{row['num_blocks']} & {row['runs']} & "
                f"{row['mean_rre']:.4f} $\\pm$ "
                f"{row['std_rre']:.4f} \\\\\n"
            )
        handle.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")


def plot_sweeps(rows, output_dir):
    figures_dir = os.path.join(output_dir, "figures")
    os.makedirs(figures_dir, exist_ok=True)
    datasets = sorted({row["dataset"] for row in rows})
    expected_figures = {
        os.path.join(figures_dir, f"{dataset}_rre_vs_{sweep}.png")
        for dataset in datasets
        for sweep in ("block_size", "block_count")
    }
    for figure_path in glob.glob(os.path.join(figures_dir, "*_rre_vs_block_*.png")):
        if figure_path not in expected_figures:
            os.remove(figure_path)
    algorithms = sorted(
        {row["algorithm"] for row in rows},
        key=lambda name: {"standard_nmf": 0, "robust_l1_nmf": 1}.get(name, 99),
    )

    for dataset in datasets:
        for sweep_name, flag, x_key, x_label in (
            ("block_size", "include_size_sweep", "block_size", "Block edge length, b (pixels)"),
            ("block_count", "include_count_sweep", "num_blocks", "Number of blocks, k"),
        ):
            fig, ax = plt.subplots(figsize=(6.4, 4.2))
            for algorithm in algorithms:
                selected = [
                    row for row in rows
                    if row["dataset"] == dataset
                    and row["algorithm"] == algorithm
                    and row[flag]
                ]
                grouped = defaultdict(list)
                for row in selected:
                    grouped[row[x_key]].append(row["rre"])
                x_values = sorted(grouped)
                means = [float(np.mean(grouped[x])) for x in x_values]
                stds = [
                    float(np.std(grouped[x], ddof=1)) if len(grouped[x]) > 1 else 0.0
                    for x in x_values
                ]
                ax.errorbar(
                    x_values,
                    means,
                    yerr=stds,
                    marker="o",
                    capsize=4,
                    label=_algorithm_label(algorithm),
                )
            ax.set_xlabel(x_label)
            ax.set_ylabel("Relative Reconstruction Error")
            ax.set_title(f"{dataset}: RRE versus {sweep_name.replace('_', ' ')}")
            ax.grid(alpha=0.25)
            ax.legend()
            fig.tight_layout()
            fig.savefig(
                os.path.join(figures_dir, f"{dataset}_rre_vs_{sweep_name}.png"),
                dpi=300,
                bbox_inches="tight",
            )
            plt.close(fig)


def plot_reconstruction_snapshots(output_dir, rows):
    figures_dir = os.path.join(output_dir, "figures", "reconstructions")
    os.makedirs(figures_dir, exist_ok=True)
    allowed_stems = {
        f"{row['dataset']}_{row['condition_id']}"
        for row in rows
        if row["run"] == 0
    }
    for figure_path in glob.glob(os.path.join(figures_dir, "*.png")):
        stem = os.path.splitext(os.path.basename(figure_path))[0]
        if stem not in allowed_stems:
            os.remove(figure_path)
    pattern = os.path.join(output_dir, "reconstructions", "*.npz")
    for snapshot_path in sorted(glob.glob(pattern)):
        stem = os.path.splitext(os.path.basename(snapshot_path))[0]
        if stem not in allowed_stems:
            continue
        with np.load(snapshot_path) as snapshot:
            image_shape = tuple(int(value) for value in snapshot["image_shape"])
            panels = (
                ("Clean", snapshot["clean"]),
                ("Corrupted", snapshot["noisy"]),
                ("Standard NMF", snapshot["standard_nmf"]),
                ("Smoothed L1-loss NMF", snapshot["robust_l1_nmf"]),
            )
            fig, axes = plt.subplots(1, 4, figsize=(9.6, 2.7))
            for axis, (title, values) in zip(axes, panels):
                axis.imshow(values.reshape(image_shape), cmap="gray", vmin=0, vmax=1)
                axis.set_title(title)
                axis.axis("off")
            fig.suptitle(stem.replace("_", " "))
            fig.tight_layout()
            fig.savefig(
                os.path.join(figures_dir, f"{stem}.png"),
                dpi=300,
                bbox_inches="tight",
            )
            plt.close(fig)


def main(argv=None):
    args = parse_args(argv)
    os.makedirs(args.output_dir, exist_ok=True)
    rows = read_results(args.results)
    summary = aggregate_results(rows)
    write_summary_csv(os.path.join(args.output_dir, "summary.csv"), summary)
    write_latex_table(os.path.join(args.output_dir, "rre_summary_table.tex"), summary)
    plot_sweeps(rows, args.output_dir)
    plot_reconstruction_snapshots(args.output_dir, rows)
    print(f"Saved summary tables and figures to {args.output_dir}")


def _algorithm_label(name):
    labels = {
        "standard_nmf": "Standard NMF",
        "robust_l1_nmf": "Smoothed L1-loss NMF",
    }
    return labels.get(name, name.replace("_", " "))


if __name__ == "__main__":
    main()
